"""Generates PAKLibCTest\\ZlibVectors.h: zlib streams made by Python's zlib, as C++ arrays for TestsImage.cpp
(an independent encoder's output for PAKLibC's inflate). The input patterns are reproduced in C++ by
pattern_a / pattern_b in TestsImage.cpp.  Usage: python gen_zlib_vectors.py"""
import os
import zlib

OUT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "ZlibVectors.h"))


def pattern_a():
    return b"PAKLibC " * 200 + bytes(range(256))


def pattern_b():
    return bytes(((i % 251) ^ (i // 997)) & 0xFF for i in range(40000))


def stream(data, level, strategy=zlib.Z_DEFAULT_STRATEGY):
    c = zlib.compressobj(level, zlib.DEFLATED, 15, 9, strategy)
    return c.compress(data) + c.flush()


def emit(name, blob):
    lines = []
    for i in range(0, len(blob), 24):
        lines.append("\t" + ", ".join("0x%02X" % b for b in blob[i:i + 24]) + ",")
    return "static const uint8_t %s[%d] = {\n%s\n};\n" % (name, len(blob), "\n".join(lines))


out = []
out.append(emit("zlib_a_dynamic", stream(pattern_a(), 9)))
out.append(emit("zlib_a_fixed", stream(pattern_a(), 9, zlib.Z_FIXED)))
out.append(emit("zlib_a_stored", stream(pattern_a()[:300], 0)))
out.append(emit("zlib_b_dynamic", stream(pattern_b(), 6)))
out.append(emit("zlib_b_huffman_only", stream(pattern_b()[:1500], 6, zlib.Z_HUFFMAN_ONLY)))
text = "// Generated by PAKLibCTest/Parity/gen_zlib_vectors.py from Python's zlib %s\n" % zlib.ZLIB_VERSION + "".join(out)
text = "#pragma once\n#include <cstdint>\n\nnamespace zlib_vectors {\n" + text + "}\n"
with open(OUT, "w", encoding="ascii", newline="\r\n") as f:
    f.write(text)
print("wrote " + OUT)
